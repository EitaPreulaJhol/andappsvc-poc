void LaunchedProcess::Close() {
  if (thread) CloseHandle(thread);
  if (process) CloseHandle(process);
  thread = nullptr;
  process = nullptr;
  pid = 0;
}

bool IsElevated() {
  HANDLE token = nullptr;
  if (!OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &token)) return false;
  TOKEN_ELEVATION elevation = {};
  DWORD returned = 0;
  const BOOL ok = GetTokenInformation(token, TokenElevation, &elevation, sizeof(elevation),
                                      &returned);
  CloseHandle(token);
  return ok != FALSE && elevation.TokenIsElevated != 0;
}

bool InjectLibrary(HANDLE process, const std::wstring& dll_path, uint64_t* module_base,
                   std::wstring* error) {
  if (GetFileAttributesW(dll_path.c_str()) == INVALID_FILE_ATTRIBUTES) {
    if (error) *error = L"payload DLL not found: " + dll_path;
    return false;
  }

  // kernel32!LoadLibraryW has the same address in every process of a session,
  // so the injector's address is valid inside the target as well.
  HMODULE kernel32 = GetModuleHandleW(L"kernel32.dll");
  auto load_library = kernel32 ? reinterpret_cast<LPTHREAD_START_ROUTINE>(reinterpret_cast<void*>(
                                    GetProcAddress(kernel32, "LoadLibraryW")))
                              : nullptr;
  if (load_library == nullptr) {
    if (error) *error = L"LoadLibraryW not found";
    return false;
  }

  const size_t bytes = (dll_path.size() + 1) * sizeof(wchar_t);
  void* remote = VirtualAllocEx(process, nullptr, bytes, MEM_COMMIT | MEM_RESERVE,
                                PAGE_READWRITE);
  if (remote == nullptr) {
    if (error) *error = L"VirtualAllocEx failed: " + Win32ErrorMessage(GetLastError());
    return false;
  }
  if (!WriteProcessMemory(process, remote, dll_path.c_str(), bytes, nullptr)) {
    if (error) *error = L"WriteProcessMemory failed: " + Win32ErrorMessage(GetLastError());
    VirtualFreeEx(process, remote, 0, MEM_RELEASE);
    return false;
  }

  HANDLE thread = CreateRemoteThread(process, nullptr, 0, load_library, remote, 0, nullptr);
  if (thread == nullptr) {
    if (error) *error = L"CreateRemoteThread(LoadLibraryW) failed: " +
                        Win32ErrorMessage(GetLastError());
    VirtualFreeEx(process, remote, 0, MEM_RELEASE);
    return false;
  }

  const DWORD wait = WaitForSingleObject(thread, 30000);
  DWORD exit_code = 0;
  GetExitCodeThread(thread, &exit_code);
  CloseHandle(thread);
  VirtualFreeEx(process, remote, 0, MEM_RELEASE);

  if (wait != WAIT_OBJECT_0) {
    if (error) *error = L"remote LoadLibraryW did not finish";
    return false;
  }
  if (exit_code == 0) {
    if (error) {
      *error = L"remote LoadLibraryW failed (the DLL could not be mapped or DllMain "
               L"returned FALSE)";
    }
    return false;
  }
  if (module_base) *module_base = exit_code;
  return true;
}

bool LaunchSuspended(const std::wstring& command_line, LaunchedProcess* launched,
                     std::wstring* error) {
  STARTUPINFOW si = {};
  si.cb = sizeof(si);
  PROCESS_INFORMATION pi = {};
  std::wstring mutable_command_line = command_line;
  if (!CreateProcessW(nullptr, mutable_command_line.data(), nullptr, nullptr, FALSE,
                      CREATE_SUSPENDED | CREATE_UNICODE_ENVIRONMENT, nullptr, nullptr, &si, &pi)) {
    if (error) *error = L"CreateProcessW failed: " + Win32ErrorMessage(GetLastError());
    return false;
  }
  launched->process = pi.hProcess;
  launched->thread = pi.hThread;
  launched->pid = pi.dwProcessId;
  return true;
}

bool WritePayloadPolicy(const std::wstring& path, const ProtectOptions& options,
                        const std::wstring& log_path, std::wstring* error) {
  std::wstring text;
  text += L"# andappsvc payload policy - generated by andappsvc_client.exe\n";
  if (!options.nt_image_path.empty()) {
    text += L"image=" + options.nt_image_path + L"\n";
  }
  if (!options.trusted_pids.empty()) {
    text += L"trusted=";
    for (size_t i = 0; i < options.trusted_pids.size(); ++i) {
      text += (i ? L"," : L"");
      text += std::to_wstring(options.trusted_pids[i]);
    }
    text += L"\n";
  }
  if (!options.blacklist_pids.empty()) {
    text += L"blacklist=";
    for (size_t i = 0; i < options.blacklist_pids.size(); ++i) {
      text += (i ? L"," : L"");
      text += std::to_wstring(options.blacklist_pids[i]);
    }
    text += L"\n";
  }
  if (options.expected_parent_pid != 0) {
    text += L"expected_parent=" + std::to_wstring(options.expected_parent_pid) + L"\n";
  }
  text += L"enable=" + std::to_wstring(options.enable ? 1 : 0) + L"\n";
  if (!log_path.empty()) text += L"log=" + log_path + L"\n";
  return WriteTextFileUtf8(path, text, error);
}

std::wstring ModuleDirectory(HMODULE module) {
  wchar_t path[MAX_PATH * 4] = {};
  if (GetModuleFileNameW(module, path, ARRAYSIZE(path)) == 0) return {};
  wchar_t* slash = wcsrchr(path, L'\\');
  if (slash == nullptr) return {};
  *slash = L'\0';
  return path;
}

